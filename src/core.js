export function dateKey(date = new Date()) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}

export function monthIndex(date = new Date()) {
  return date.getFullYear() * 12 + date.getMonth();
}

export function monthParts(index) {
  const year = Math.floor(index / 12);
  return { year, month: index - year * 12 };
}

function parseDateKey(key) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(key || "");
  if (!match) return null;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const date = new Date(Date.UTC(year, month - 1, day));
  if (date.getUTCFullYear() !== year || date.getUTCMonth() !== month - 1 || date.getUTCDate() !== day) return null;
  return date;
}

export function questionsForDate(key) {
  const date = parseDateKey(key);
  if (!date) throw new Error("日付形式が正しくありません。");
  const anchor = Date.UTC(2026, 8, 11);
  const serial = Math.floor((date.getTime() - anchor) / 86_400_000);
  const dayIndex = ((serial % 30) + 30) % 30;
  return QUESTION_DAYS[dayIndex];
}

export function fallbackSummary(answers) {
  const counts = answers.reduce((result, answer) => {
    result[answer.type] = (result[answer.type] || 0) + 1;
    return result;
  }, {});
  if ((counts.no || 0) >= 2) return "今日は分からなかった場面もありました。見えたことと分からなかったことを、そのまま今日の記録として残します。";
  if ((counts.kinda || 0) >= 2) return "今日は少し気づいた場面をいくつか記録しました。次に似た場面があったときも、見えたことをそのまま残してみましょう。";
  return "今日は、やりとり・行動や遊び・場面による変化の3つの視点で振り返りました。見えたことを、そのまま今日の記録として残します。";
}

export function recordQuestions(record, key) {
  if (record?.answers?.every((answer) => answer.question)) {
    return record.answers.map((answer) => ({ id: answer.questionId, emoji: answer.emoji || "🌱", text: answer.question, domain: answer.domain }));
  }
  return questionsForDate(key);
}

export function recordsForMonth(records, year, month) {
  const prefix = `${year}-${String(month + 1).padStart(2, "0")}-`;
  return Object.entries(records || {})
    .filter(([key]) => key.startsWith(prefix))
    .sort(([first], [second]) => first.localeCompare(second));
}

